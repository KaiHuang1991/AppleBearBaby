export function getOemFaqs(locale = 'en') {
  return OEM_FAQS_I18N[locale] || OEM_FAQS
}

export function getProductFaqs(locale = 'en') {
  return getOemFaqs(locale).filter((_, index) => PRODUCT_FAQ_INDEXES.includes(index))
}

export const PRODUCT_FAQS = getProductFaqs('en')

export function buildFaqPageJsonLd(origin = '', faqs = OEM_FAQS, locale = 'en') {
  const site = String(origin || '').replace(/\/$/, '')
  const prefix = locale && locale !== 'en' ? `/${locale}` : ''
  return {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    inLanguage: locale === 'zh' ? 'zh-Hans' : locale,
    mainEntity: faqs.map((item) => ({
      '@type': 'Question',
      name: item.question,
      acceptedAnswer: {
        '@type': 'Answer',
        text: item.answer,
      },
    })),
    url: site ? `${site}${prefix}/faq` : undefined,
    isPartOf: site
      ? { '@type': 'WebSite', name: 'AppleBear Baby', url: site }
      : undefined,
  }
}

export function faqBodyHtml(faqs = OEM_FAQS) {
  return faqs
    .map(
      (item) =>
        `<h2>${escapeFaq(item.question)}</h2><p>${escapeFaq(item.answer)}</p>`
    )
    .join('')
}

export function buildInlineFaqJsonLd(faqs = PRODUCT_FAQS) {
  return {
    '@type': 'FAQPage',
    mainEntity: faqs.map((item) => ({
      '@type': 'Question',
      name: item.question,
      acceptedAnswer: {
        '@type': 'Answer',
        text: item.answer,
      },
    })),
  }
}

